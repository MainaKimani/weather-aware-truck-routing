"""commit-msg hook: enforce Conventional Commits on the subject line.

Merge, revert and fixup/squash subjects generated by git are let through.
"""

import re
import sys

TYPES = "feat|fix|refactor|perf|docs|style|test|build|ci|chore|revert"
SUBJECT = re.compile(rf"^(?:{TYPES})(?:\([a-z0-9-]+\))?!?: \S.*$")
PASSTHROUGH = re.compile(r"^(?:Merge |Revert \"|fixup! |squash! |amend! )")
MAX_SUBJECT = 72


def main(path: str) -> int:
    with open(path, encoding="utf-8") as f:
        lines = [line for line in f.read().splitlines() if not line.startswith("#")]
    subject = lines[0] if lines else ""

    if PASSTHROUGH.match(subject):
        return 0
    errors = []
    if not SUBJECT.match(subject):
        errors.append(f"subject must be '<type>(<scope>): <subject>' with type in {TYPES}")
    if len(subject) > MAX_SUBJECT:
        errors.append(f"subject is {len(subject)} chars; keep it under {MAX_SUBJECT}")
    if subject.endswith("."):
        errors.append("subject must not end with a period")
    if len(lines) > 1 and lines[1].strip():
        errors.append("leave a blank line between subject and body")

    for error in errors:
        print(f"commit-msg: {error}", file=sys.stderr)
    if errors:
        print(f"  got: {subject!r}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
